/**
 * 按角色姓名与别名查找头像角色的外观与常驻穿着档案。
 */
export function getAvatarCharacterProfile(name?: string, aliases?: readonly string[]): AvatarCharacterProfile | undefined {
  if (!name && (!aliases || !aliases.length)) return undefined;
  const candidates = [name, ...(aliases ?? [])]
    .map((v) => (v ?? '').trim())
    .filter(Boolean);
  for (const candidate of candidates) {
    if (AVATAR_CHARACTER_PROFILES[candidate]) return AVATAR_CHARACTER_PROFILES[candidate];
  }
  for (const candidate of candidates) {
    for (const profile of Object.values(AVATAR_CHARACTER_PROFILES)) {
      if (profile.name === candidate || profile.aliases?.includes(candidate)) {
        return profile;
      }
    }
  }
  return undefined;
}
