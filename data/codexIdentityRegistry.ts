const prefixToCategory = new Map(
  Object.values(CODEX_CATEGORY_POLICIES).map((policy) => [policy.machineIdPrefix, policy.key]),
);

export const CODEX_BUNDLED_IDENTITY_REGISTRY: readonly 图鉴内置身份注册项[] = RAW_IDENTITY_GROUPS.flatMap(
  ([presetId, sourceFile, entries]) => entries.map(([id, legacyId, sourceTitle], sourceIndex) => {
    const category = prefixToCategory.get(id.slice(0, 2));
    if (!category) throw new Error(`图鉴身份注册表包含未知前缀：${id}`);
    return { id, legacyId, category, presetId, sourceFile, sourceIndex, sourceTitle };
  }),
);

const identityBySource = new Map(
  CODEX_BUNDLED_IDENTITY_REGISTRY.map((entry) => [`${entry.presetId}:${entry.sourceIndex}`, entry]),
);

const identityByAnyId = new Map<string, 图鉴内置身份注册项>();
for (const entry of CODEX_BUNDLED_IDENTITY_REGISTRY) {
  identityByAnyId.set(entry.id, entry);
  identityByAnyId.set(entry.legacyId, entry);
}

export function resolveBundledCodexIdentity(
  presetId: string,
  sourceIndex: number,
  sourceId?: string,
  sourceTitle?: string,
): 图鉴内置身份注册项 | undefined {
  const entry = identityBySource.get(`${presetId}:${sourceIndex}`);
  if (!entry) return undefined;
  const legacyId = sourceId?.trim() || `${presetId}_${sourceIndex + 1}`;
  const title = sourceTitle?.trim();
  return entry.legacyId === legacyId && (!title || entry.sourceTitle === title) ? entry : undefined;
}

export function findBundledCodexIdentity(id: string): 图鉴内置身份注册项 | undefined {
  return identityByAnyId.get(id.trim());
}

export function resolveCodexMachineId(id: string): string {
  return findBundledCodexIdentity(id)?.id ?? id;
}
